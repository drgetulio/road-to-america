export const dentro = (p: Ponto, poli: Ponto[]): boolean => {
  let c = false;
  for (let i = 0, j = poli.length - 1; i < poli.length; j = i++) {
    const [xi, yi] = poli[i];
    const [xj, yj] = poli[j];
    if (yi > p[1] !== yj > p[1] && p[0] < ((xj - xi) * (p[1] - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};

export type Projecao = { lon0: number; lat0: number; escala: number; x0: number; y0: number };

export const projetar = (pr: Projecao, [lon, lat]: Ponto): [number, number] => [
  pr.x0 + (lon - pr.lon0) * pr.escala * Math.cos((pr.lat0 * Math.PI) / 180),
  pr.y0 - (lat - pr.lat0) * pr.escala,
];

export type PontoMapa = { x: number; y: number; regiao: "eua" | "brasil" | "outro"; lon: number; lat: number };

/** Grade de pontos (meio-tom) dentro dos contornos. */
export const pontilhar = (
  pr: Projecao,
  limites: { lonMin: number; lonMax: number; latMin: number; latMax: number },
  passoGraus: number,
  regioes: { eua?: boolean; brasil?: boolean; outros?: boolean },
): PontoMapa[] => {
  const out: PontoMapa[] = [];
  for (let lat = limites.latMax; lat >= limites.latMin; lat -= passoGraus) {
    for (let lon = limites.lonMin; lon <= limites.lonMax; lon += passoGraus / Math.cos((pr.lat0 * Math.PI) / 180)) {
      const p: Ponto = [lon, lat];
      let regiao: PontoMapa["regiao"] | null = null;
      if (dentro(p, EUA)) regiao = regioes.eua ? "eua" : null;
      else if (dentro(p, BRASIL)) regiao = regioes.brasil ? "brasil" : null;
      else if (regioes.outros && (dentro(p, AMERICA_SUL) || dentro(p, MEXICO_AC) || dentro(p, CANADA))) regiao = "outro";
      if (regiao) {
        const [x, y] = projetar(pr, p);
        out.push({ x, y, regiao, lon, lat });
      }
    }
  }
  return out;
};
